export type AppTheme = typeof CombinedDefaultTheme & { colors: { warning: string } };

// Picker order: light themes, then dark. Names live in i18n under themes.<id>.
export const APP_THEMES = [
  { id: "petroleum", theme: AppDefaultTheme },
  { id: "havsbris", theme: HavsbrisTheme },
  { id: "midsommar", theme: MidsommarTheme },
  { id: "lingonris", theme: LingonrisTheme },
  { id: "bergsdimma", theme: BergsdimmaTheme },
  { id: "bivack", theme: AppDarkTheme },
  { id: "stjarnhimmel", theme: StjarnhimmelTheme },
  { id: "norrsken", theme: NorrskenTheme },
  { id: "ljungnatt", theme: LjungnattTheme },
  { id: "skifferkvall", theme: SkifferkvallTheme },
] as const satisfies readonly { id: string; theme: AppTheme }[];

export type ThemeId = (typeof APP_THEMES)[number]["id"];
export type ThemeChoice = ThemeId | "auto";

export function isThemeChoice(value: unknown): value is ThemeChoice {
  return value === "auto" || APP_THEMES.some((t) => t.id === value);
}

export function resolveTheme(choice: ThemeChoice, colorScheme: string | null | undefined): AppTheme {
  if (choice === "auto") return colorScheme === "dark" ? AppDarkTheme : AppDefaultTheme;
  return APP_THEMES.find((t) => t.id === choice)?.theme ?? AppDefaultTheme;
}
