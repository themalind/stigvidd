#!/usr/bin/env node
// PreToolUse(Write|Edit|MultiEdit|NotebookEdit): the files something else owns.
//
// Each of these accepts a hand edit and then throws it away, at a moment far from the
// edit — which is the shape that costs a session, because the edit *looked* like it
// worked and the tests that follow are testing the old content:
//
//   * web/src/api/generated/**  is orval output.  `npm run generate:api` overwrites it
//     wholesale, and the Jenkinsfile web stage regenerates and then runs
//     `git diff --exit-code -- src/api/generated`, so a hand edit is a red build with a
//     message about staleness rather than about your change.
//   * web/openapi.json is a SNAPSHOT THE TEST SUITE WRITES.  When the API drifts,
//     OpenApiContractTests rewrites this file itself and then fails once, telling you to
//     regenerate the client.  Editing it by hand to "fix" the mismatch inverts the
//     direction the data flows: the API is the source, the file is the record.
//   * *ModelSnapshot.cs and *.Designer.cs are EF Core's model, not source.  A hand edit
//     desynchronises the recorded model from the schema, and the next
//     `dotnet ef migrations add` scaffolds a diff against your edit instead of against
//     the database — silently, because the code compiles either way.
//
// A migration's OWN .cs body is a different case and is only WARNED about: the
// *PostGIS* migrations in this repo carry hand-written SQL by design
// (docs/spatial-data.md), so editing one is legitimate when it is a migration you just
// scaffolded and have not applied.
//
// Self-test: `node .claude/hooks/guard-generated-files.mjs --self-test`
import process from "node:process";
import { readEvent, repoRoot, relKey, under, deny, speak, checker } from "./lib.mjs";

const GENERATED_DIR = "web/src/api/generated";
const MIGRATIONS_DIR = "backend/infrastructure/migrations";

export function decide(toolName, input) {
  if (!/^(Write|Edit|MultiEdit|NotebookEdit)$/.test(toolName)) return null;
  const root = repoRoot();
  const raw = input?.file_path ?? input?.notebook_path;
  const key = relKey(root, raw) ?? relKey("/", String(raw ?? "").replace(/\\/g, "/"));
  if (!key) return null;
  return classify(key);
}

/**
 * Split out so the self-test can drive it with repo-relative keys directly.
 *
 * Lowercased UNCONDITIONALLY, not via fold(): these are fixed repo paths, spelled
 * `backend/Infrastructure/Migrations` on every platform, so matching them is a
 * case-insensitive string question and not a filesystem one. fold() is a no-op off
 * win32, and using it here left every mixed-case pattern below dead on Linux — caught
 * by this hook's own self-test, which is the whole reason each one asserts both shapes.
 */
export function classify(keyIn) {
  const key = String(keyIn).toLowerCase();

  if (under(key, GENERATED_DIR))
    return [
      "deny",
      `${keyIn} is generated by orval and a hand edit is thrown away.\n` +
        "The API contract is the source: change the controller / WebDataContracts DTO, " +
        "let the backend tests rewrite web/openapi.json, then regenerate:\n" +
        "  cd web && npm run generate:api\n" +
        "The Jenkinsfile web stage regenerates and runs " +
        "`git diff --exit-code -- src/api/generated`, so a hand edit fails the build " +
        "with a staleness message rather than one about your change.",
    ];

  if (key === "web/openapi.json")
    return [
      "deny",
      "web/openapi.json is a snapshot the test suite writes, not a file to edit.\n" +
        "OpenApiContractTests rewrites it itself when the API drifts and then fails " +
        "once. The fix is to run the backend tests, review the rewrite, then:\n" +
        "  cd web && npm run generate:api      # and commit both files\n" +
        "Editing it by hand reverses the direction the data flows.",
    ];

  if (under(key, MIGRATIONS_DIR)) {
    if (/modelsnapshot\.cs$/.test(key))
      return [
        "deny",
        `${keyIn} is EF Core's record of the model, not source.\n` +
          "A hand edit desynchronises it from the schema, and the next " +
          "`dotnet ef migrations add` then diffs against your edit instead of against " +
          "the database — silently, because it compiles either way.\n" +
          "Change the entity or the DbContext configuration and scaffold a migration:\n" +
          "  cd backend && dotnet tool restore && dotnet restore\n" +
          "  dotnet ef migrations add <Name> --project Infrastructure",
      ];
    if (/\.designer\.cs$/.test(key))
      return [
        "deny",
        `${keyIn} is scaffolded by EF Core alongside its migration.\n` +
          "Edit the migration's own .cs body if you need different SQL; if the model " +
          "itself is wrong, remove and re-add the migration:\n" +
          "  cd backend && dotnet ef migrations remove --project Infrastructure",
      ];
    if (/\.cs$/.test(key))
      return [
        "warn",
        `${keyIn} is a migration body. Editing one is legitimate — the *PostGIS* ` +
          "migrations here carry hand-written SQL by design (docs/spatial-data.md) — " +
          "but only for a migration you have just scaffolded and NOT applied.\n" +
          "An applied migration has already run on every database that has it in " +
          "__EFMigrationsHistory; those will never re-run it. Add a new migration " +
          "instead, and leave *ModelSnapshot.cs to EF either way.",
      ];
  }
  return null;
}

function main() {
  if (process.argv.includes("--self-test")) return selfTest();
  const ev = readEvent();
  const d = decide(String(ev.tool_name ?? ""), ev.tool_input ?? {});
  if (!d) return 0;
  return d[0] === "deny" ? deny(d[1]) : speak(d[1]);
}

function selfTest() {
  const { ok, done } = checker("guard-generated-files");
  // Both separator shapes for every denied path: the backslash form is what the Edit
  // tool sends on Windows, and matching only the POSIX form fails OPEN there.
  const cases = [
    ["web/src/api/generated/stigvidd.ts", "deny"],
    ["web\\src\\api\\generated\\stigvidd.ts", "deny"],
    ["web/src/api/generated/model/facility.ts", "deny"],
    ["web/openapi.json", "deny"],
    ["backend/Infrastructure/Migrations/StigViddDbContextModelSnapshot.cs", "deny"],
    ["backend\\Infrastructure\\Migrations\\StigViddDbContextModelSnapshot.cs", "deny"],
    ["backend/Infrastructure/Migrations/20260523120007_PostGIS.Designer.cs", "deny"],
    ["backend/Infrastructure/Migrations/20260523120007_PostGIS.cs", "warn"],
    // Must stay silent — a guard that fires on ordinary work gets switched off.
    ["web/src/pages/Facilities.tsx", null],
    ["web/src/api/mutator.ts", null],
    ["web/orval.config.ts", null],
    ["backend/Core/Services/FacilityService.cs", null],
    ["app/src/api/map-markers.ts", null],
  ];
  for (const [p, want] of cases) {
    const got = classify(p.replace(/\\/g, "/"));
    ok(
      (got?.[0] ?? null) === want,
      `classify(${p}) => ${got?.[0] ?? "null"}, expected ${want ?? "null"}`,
    );
    if (want) ok((got?.[1] ?? "").length > 40, `${p} denied with no usable instruction`);
  }
  // The tool-name gate: a Read of a generated file is fine, only writes are not.
  ok(decide("Read", { file_path: "web/src/api/generated/x.ts" }) === null,
     "Read of a generated file was not left alone");
  ok(decide("Bash", { command: "cat web/openapi.json" }) === null,
     "Bash was routed into the write guard");
  return done(cases.length + 2);
}

process.exit(main());
